const fold = (value: string) => value.normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/\s+/g, " ").trim().toLowerCase();
const visible = (el: Element) => (el as HTMLElement).getClientRects().length > 0;

export function findTarget(specs: TargetSpec[] | undefined, root: ParentNode = document): HTMLElement | null {
  for (const spec of specs ?? []) {
    let list: Element[];
    try { list = Array.from(root.querySelectorAll(spec.css)); } catch { continue; }
    if (spec.text) {
      const wanted = fold(spec.text);
      list = list.filter(el => fold(el.textContent ?? "").includes(wanted) || fold(el.getAttribute("aria-label") ?? "") === wanted);
      // fica só com o elemento mais interno que contém o texto
      list = list.filter(el => !list.some(other => other !== el && el.contains(other)));
    }
    let found = list.find(visible) as HTMLElement | undefined;
    for (let i = 0; found && i < (spec.up ?? 0); i++) found = (found.parentElement ?? found) as HTMLElement;
    if (found) return found;
  }
  return null;
}
